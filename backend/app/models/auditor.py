import json
from datetime import datetime, timezone
from sqlalchemy import Column, String, Text, Boolean, ForeignKey
from sqlalchemy.orm import relationship
from app.database import Base


class AuditedCaseModel(Base):
    """
    SQLAlchemy model for persistent Audited Cases generated by the Auditor Agent (Module 3E).
    Serves as the final evidence-accountability ledger for an investigation,
    recording verified claims, contradictions, uncertainties, unsupported claims,
    and tool execution history.
    """
    __tablename__ = "audited_cases"

    id = Column(String, primary_key=True, index=True)  # e.g., "CASE-001"
    investigation_id = Column(String, ForeignKey("investigations.id"), nullable=False, index=True)
    claims = Column(Text, nullable=False, default="[]")  # JSON-serialized list of audited claims
    contradictions = Column(Text, nullable=False, default="[]")  # JSON-serialized list
    uncertainties = Column(Text, nullable=False, default="[]")  # JSON-serialized list
    unsupported_claims = Column(Text, nullable=False, default="[]")  # JSON-serialized list
    tool_executions = Column(Text, nullable=False, default="[]")  # JSON-serialized list of tool logs
    final_conclusion = Column(Text, nullable=False)
    audit_verified = Column(Boolean, nullable=False, default=True)
    created_at = Column(
        String,
        nullable=False,
        default=lambda: datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
    )

    # Relationship to InvestigationModel
    investigation = relationship("InvestigationModel", back_populates="audited_cases")

    def get_claims(self):
        try:
            return json.loads(self.claims)
        except Exception:
            return []

    def get_contradictions(self):
        try:
            return json.loads(self.contradictions)
        except Exception:
            return []

    def get_uncertainties(self):
        try:
            return json.loads(self.uncertainties)
        except Exception:
            return []

    def get_unsupported_claims(self):
        try:
            return json.loads(self.unsupported_claims)
        except Exception:
            return []

    def get_tool_executions(self):
        try:
            return json.loads(self.tool_executions)
        except Exception:
            return []
