"""
Pydantic Schemas for Multi-Agent Swarm Orchestration (Module 3Q)
Agentic SOC — Auditable AI Security Operations Center
"""

from typing import List, Optional, Dict, Any, Literal
from pydantic import BaseModel, Field


class AgentResponse(BaseModel):
    """Schema representing one of the 5 core SOC agents."""
    id: str = Field(..., description="Unique agent identifier (e.g. agent-planner)")
    name: str = Field(..., description="Agent display name (e.g. Planner Agent)")
    role: str = Field(..., description="Primary functional responsibility")
    status: Literal["IDLE", "RUNNING", "COMPLETED", "DEGRADED"] = Field(..., description="Operational state")
    current_task: str = Field(..., description="Current in-flight or completed task")
    execution_time_ms: int = Field(..., description="Cumulative execution time in milliseconds")
    actions_count: int = Field(..., description="Total actions recorded by this agent")
    evidence_generated: int = Field(..., description="Number of forensic evidence items created or referenced")
    capabilities: List[str] = Field(default_factory=list, description="Tool registry and analysis capabilities")
    last_active_at: str = Field(..., description="Timestamp of last activity")
    created_at: str = Field(..., description="Agent registration timestamp")


class AgentActivityResponse(BaseModel):
    """Schema for an individual chronological event emitted by an agent."""
    id: str = Field(..., description="Activity ID (e.g. ACT-001)")
    investigation_id: Optional[str] = Field(None, description="Associated investigation ID")
    agent_id: str = Field(..., description="Agent identifier")
    agent_name: str = Field(..., description="Agent display name")
    action: str = Field(..., description="Concise action description")
    details: str = Field(..., description="Extended action details")
    evidence_ids: List[str] = Field(default_factory=list, description="Referenced evidence IDs")
    timestamp: str = Field(..., description="Time of event (HH:MM:SS)")
    full_datetime: str = Field(..., description="Full UTC datetime")


class AgentSwarmSummary(BaseModel):
    """Executive KPI summary of the multi-agent swarm."""
    total_agents: int = Field(default=5, description="Total registered agents")
    active_agents: int = Field(..., description="Agents currently running or active")
    idle_agents: int = Field(..., description="Agents currently in idle standby")
    completed_agents: int = Field(..., description="Agents with completed tasks")
    total_actions: int = Field(..., description="Cumulative actions executed across all agents")
    total_evidence_generated: int = Field(..., description="Total forensic artifacts produced")
    swarm_status: str = Field(default="OPTIMAL", description="Swarm health status (OPTIMAL, DEGRADED)")
    average_execution_time_ms: float = Field(..., description="Mean execution latency in ms")


class AnalystClaim(BaseModel):
    """Structured claim generated by the Analyst Agent."""
    claim_id: str = Field(..., description="Sequential claim identifier (e.g. CLM-001)")
    statement: str = Field(..., description="Analytical claim proposition")
    supporting_evidence_ids: List[str] = Field(default_factory=list, description="Directly corroborating evidence IDs")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Preliminary confidence level (0.0 to 1.0)")
    threat_attribution_hypothesis: Optional[str] = Field(None, description="Hypothesized attribution if evidence exists")
    mitre_tactics: List[str] = Field(default_factory=list, description="Mapped MITRE ATT&CK tactics")


class AnalystRequestPayload(BaseModel):
    """Payload to trigger Analyst Agent reasoning on an investigation."""
    investigation_id: str = Field(..., description="Target investigation ID (e.g. INV-001)")
    analyst_notes: Optional[str] = Field(None, description="Optional steering instructions for analysis")
    include_threat_intel: bool = Field(default=True, description="Whether to query reputation intelligence")


class AnalystResponse(BaseModel):
    """Structured hypothesis and synthesized claims produced by Analyst Agent."""
    investigation_id: str = Field(..., description="Investigation ID")
    preliminary_hypothesis: str = Field(..., description="Comprehensive investigative hypothesis")
    claims: List[AnalystClaim] = Field(default_factory=list, description="Synthesized claims tied to evidence")
    overall_confidence: float = Field(..., description="Aggregate analyst confidence score (0.0 to 1.0)")
    evidence_analyzed_count: int = Field(..., description="Count of evidence items analyzed")
    recommended_next_action: str = Field(..., description="Recommended workflow progression (e.g. CRITIC_REVIEW)")
    created_at: str = Field(..., description="Timestamp of analysis generation")


class SwarmOrchestratePayload(BaseModel):
    """Payload to trigger autonomous multi-agent swarm orchestration."""
    investigation_id: str = Field(..., description="Target investigation ID")
    auto_contain: bool = Field(default=False, description="Whether to propose containment actions")


class SwarmOrchestrateResponse(BaseModel):
    """Result of multi-agent swarm orchestration cycle."""
    investigation_id: str = Field(..., description="Target investigation ID")
    cycle_id: str = Field(..., description="Orchestration execution ID")
    status: str = Field(default="COMPLETED", description="Orchestration outcome status")
    stages_executed: List[str] = Field(..., description="Ordered list of executed agent stages")
    planner_steps_count: int = Field(..., description="Steps planned by Planner Agent")
    tool_executions_count: int = Field(..., description="Tools executed by Tool Agent")
    analyst_claims_count: int = Field(..., description="Claims synthesized by Analyst Agent")
    critic_objections_count: int = Field(..., description="Objections flagged by Critic Agent")
    auditor_status: str = Field(..., description="Final adjudication verdict from Auditor Agent")
    total_duration_ms: int = Field(..., description="Total elapsed orchestration time in ms")
    timestamp: str = Field(..., description="Execution timestamp")
