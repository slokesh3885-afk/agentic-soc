from typing import List, Optional, Any, Dict
from pydantic import BaseModel, ConfigDict, Field, model_validator


class AuditClaimInput(BaseModel):
    """Input claim for the Auditor Agent."""
    claim: str = Field(..., min_length=1, description="Claim statement to audit against evidence")
    evidence_ids: List[str] = Field(default_factory=list, description="Referenced evidence IDs")

    @model_validator(mode="before")
    @classmethod
    def normalize_aliases(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "evidence_ids" not in data and "evidenceIds" in data:
                data["evidence_ids"] = data["evidenceIds"]
        return data


class AuditorRequest(BaseModel):
    """Request payload sent to Auditor Agent."""
    investigation_id: Optional[str] = Field(default=None, description="Investigation ID")
    claims: List[AuditClaimInput] = Field(default_factory=list, description="Claims to evaluate")
    critic_findings: Optional[List[Dict[str, Any]]] = Field(default=None, description="Optional Critic findings/objections")
    final_conclusion: Optional[str] = Field(default=None, description="Draft final conclusion")

    @model_validator(mode="before")
    @classmethod
    def normalize_aliases(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "investigation_id" not in data and "investigationId" in data:
                data["investigation_id"] = data["investigationId"]
            if "critic_findings" not in data and "criticFindings" in data:
                data["critic_findings"] = data["criticFindings"]
            if "final_conclusion" not in data and "finalConclusion" in data:
                data["final_conclusion"] = data["finalConclusion"]
        return data


class AuditedClaimItem(BaseModel):
    """Audited evaluation of an individual claim."""
    claim: str
    evidence_ids: List[str] = Field(default_factory=list)
    status: str  # SUPPORTED, UNSUPPORTED, CONTRADICTED, UNCERTAIN, INVALID_EVIDENCE_REFERENCE
    confidence: str  # SUPPORTED, UNSUPPORTED, CONTRADICTED, UNCERTAIN
    reason: str
    evidence_integrity_verified: bool = True

    # Frontend camelCase convenience aliases
    evidenceIds: Optional[List[str]] = None
    evidenceIntegrityVerified: Optional[bool] = None

    @model_validator(mode="after")
    def populate_camel_case(self) -> "AuditedClaimItem":
        self.evidenceIds = self.evidence_ids
        self.evidenceIntegrityVerified = self.evidence_integrity_verified
        return self


class AuditedToolExecutionItem(BaseModel):
    """Tool execution audit record included in the case file."""
    id: str
    tool_name: str
    input: Any
    output: Any
    timestamp: str
    success: bool
    evidence_id: Optional[str] = None

    toolName: Optional[str] = None
    evidenceId: Optional[str] = None

    @model_validator(mode="after")
    def populate_camel_case(self) -> "AuditedToolExecutionItem":
        self.toolName = self.tool_name
        self.evidenceId = self.evidence_id
        return self


class AuditedCaseResponse(BaseModel):
    """Structured audited case file generated by Auditor Agent (Module 3E)."""
    model_config = ConfigDict(from_attributes=True)

    case_id: str  # e.g., "CASE-001"
    investigation_id: str
    claims: List[AuditedClaimItem] = Field(default_factory=list)
    contradictions: List[str] = Field(default_factory=list)
    uncertainties: List[str] = Field(default_factory=list)
    unsupported_claims: List[str] = Field(default_factory=list)
    tool_executions: List[AuditedToolExecutionItem] = Field(default_factory=list)
    final_conclusion: str
    audit_verified: bool = True
    created_at: str

    # Frontend camelCase convenience aliases
    caseId: Optional[str] = None
    investigationId: Optional[str] = None
    unsupportedClaims: Optional[List[str]] = None
    toolExecutions: Optional[List[AuditedToolExecutionItem]] = None
    finalConclusion: Optional[str] = None
    auditVerified: Optional[bool] = None
    createdAt: Optional[str] = None

    @model_validator(mode="after")
    def populate_camel_case(self) -> "AuditedCaseResponse":
        self.caseId = self.case_id
        self.investigationId = self.investigation_id
        self.unsupportedClaims = self.unsupported_claims
        self.toolExecutions = self.tool_executions
        self.finalConclusion = self.final_conclusion
        self.auditVerified = self.audit_verified
        self.createdAt = self.created_at
        return self
