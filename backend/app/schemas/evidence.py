from enum import Enum
from typing import Optional, Dict, Any
from pydantic import BaseModel, ConfigDict, Field, model_validator


class EvidenceType(str, Enum):
    """Controlled enum of authorized evidence types."""
    SIEM_LOG = "SIEM_LOG"
    EDR_EVENT = "EDR_EVENT"
    HASH_LOOKUP = "HASH_LOOKUP"
    SANDBOX_RESULT = "SANDBOX_RESULT"
    WHOIS_RESULT = "WHOIS_RESULT"
    YARA_RESULT = "YARA_RESULT"
    DNS_EVENT = "DNS_EVENT"
    PROCESS_EVENT = "PROCESS_EVENT"
    FILE_EVENT = "FILE_EVENT"
    OTHER = "OTHER"


class EvidenceCreate(BaseModel):
    """Schema for creating a new evidence item.
    Note: Client cannot supply ID, content_hash, or created_at; they are generated by the engine.
    """
    evidence_type: EvidenceType
    source: str = Field(..., min_length=1, description="Source system (e.g. Mock SIEM, CrowdStrike, Zeek)")
    raw_output: str = Field(..., min_length=1, description="Raw, unaltered evidence output string")
    timestamp: Optional[str] = Field(default=None, description="Observed event timestamp")
    query: Optional[str] = Field(default="", description="Query or command executed to gather evidence")
    status: Optional[str] = Field(default="COLLECTED", description="Status of evidence (e.g. COLLECTED, VERIFIED)")

    @model_validator(mode="before")
    @classmethod
    def normalize_aliases(cls, data: Any) -> Any:
        if isinstance(data, dict):
            # Support camelCase aliases if passed from frontend
            if "evidence_type" not in data and "evidenceType" in data:
                data["evidence_type"] = data["evidenceType"]
            if "raw_output" not in data and "rawOutput" in data:
                data["raw_output"] = data["rawOutput"]
        return data


class EvidenceResponse(BaseModel):
    """Schema for returning evidence details to the client."""
    model_config = ConfigDict(from_attributes=True)

    id: str
    investigation_id: str
    evidence_type: str
    source: str
    timestamp: str
    query: Optional[str] = ""
    raw_output: str
    content_hash: str  # SHA-256 hash computed at creation
    status: str = "COLLECTED"
    created_at: str
    integrity_verified: bool = True

    # Frontend camelCase convenience aliases
    evidenceType: Optional[str] = None
    rawOutput: Optional[str] = None
    contentHash: Optional[str] = None
    createdAt: Optional[str] = None

    @model_validator(mode="after")
    def populate_aliases(self) -> "EvidenceResponse":
        if self.evidenceType is None:
            self.evidenceType = self.evidence_type
        if self.rawOutput is None:
            self.rawOutput = self.raw_output
        if self.contentHash is None:
            self.contentHash = self.content_hash
        if self.createdAt is None:
            self.createdAt = self.created_at
        return self


class EvidenceIntegrityCheck(BaseModel):
    """Schema for evidence integrity verification result."""
    evidence_id: str
    valid: bool
    content_hash: str
    recalculated_hash: str
    timestamp_verified: str


