from typing import List, Optional, Any
from pydantic import BaseModel, ConfigDict, Field, model_validator


class PlanStep(BaseModel):
    """Individual proposed step in an investigation plan referencing an allow-listed tool."""
    step: int = Field(..., ge=1, description="Sequential step number (1, 2, ...)")
    action: str = Field(..., min_length=1, description="Action description")
    tool_name: str = Field(..., min_length=1, description="Allow-listed tool name to be used")
    reason: str = Field(..., min_length=1, description="Forensic rationale for this step")
    status: str = Field(default="PROPOSED", description="Step status (strictly PROPOSED)")

    # Frontend camelCase alias
    toolName: Optional[str] = None

    @model_validator(mode="after")
    def populate_aliases(self) -> "PlanStep":
        if self.toolName is None:
            self.toolName = self.tool_name
        return self


class PlanCreateRequest(BaseModel):
    """Request payload to generate or update an investigation plan."""
    alert: Optional[str] = Field(
        default=None,
        description="Alert title or context. If omitted, fetched automatically from parent investigation.",
    )


class InvestigationPlanResponse(BaseModel):
    """Structured plan generated by the Planner Agent."""
    model_config = ConfigDict(from_attributes=True)

    investigation_id: str
    alert: str
    plan: List[PlanStep]
    planner_status: str = "PROPOSED"
    created_at: str

    # Frontend camelCase aliases
    investigationId: Optional[str] = None
    plannerStatus: Optional[str] = None
    createdAt: Optional[str] = None

    @model_validator(mode="after")
    def populate_aliases(self) -> "InvestigationPlanResponse":
        if self.investigationId is None:
            self.investigationId = self.investigation_id
        if self.plannerStatus is None:
            self.plannerStatus = self.planner_status
        if self.createdAt is None:
            self.createdAt = self.created_at
        return self
